#!/usr/bin/env python3
"""Build six original geometric sample scenes, pre-sized to avoid transform RAM.

Generation uses the same Pillow environment as passport_font.py. No downloaded
or personal images are used. Both letterboxed viewport sizes are compiled into
read-only Flash as RGB565; no full-screen heap buffer is required.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "assets/images/passport"

def main():
    DEST.mkdir(parents=True, exist_ok=True)
    code = ['/* Generated by tools/passport_photos.py; original project examples. */',
            '#include "passport_photos.h"']
    descriptors = []
    for n, (w, h) in enumerate([(320,240),(240,320),(320,240),(300,300),(240,320),(320,240)]):
        im = Image.new('RGB', (w,h), ['#a7c4bb','#d5b5a3','#a3b8cc','#b9b7d4','#acc7b0','#d8bd9b'][n])
        d = ImageDraw.Draw(im)
        d.ellipse((w*.62,h*.12,w*.82,h*.12+w*.2), fill='#f4dc9a')
        d.polygon([(0,h*.72),(w*.25,h*.32),(w*.57,h*.78),(w*.76,h*.4),(w,h*.73),(w,h),(0,h)],fill='#648d88')
        d.polygon([(0,h*.85),(w*.32,h*.64),(w*.7,h*.86),(w,h*.62),(w,h),(0,h)],fill='#325e60')
        d.polygon([(w*.38,h),(w*.48,h*.73),(w*.56,h*.73),(w*.7,h)],fill='#d9c7a1')
        im.save(DEST / f'scene-{n+1}.png')
        for full, (bw,bh) in enumerate([(208,208),(240,320)]):
            scale=min(bw/w,bh/h)
            sized=im.resize((int(w*scale),int(h*scale)),Image.Resampling.LANCZOS)
            data=[]
            for r,g,b in sized.getdata():
                pixel=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
                data.extend([pixel&255,pixel>>8])
            name=f'photo_{n}_{full}'
            code.append(f'static const uint8_t {name}_data[] = {{')
            code.extend(','.join(f'0x{b:02x}' for b in data[i:i+24])+',' for i in range(0,len(data),24))
            code.append('};')
            code.append(f'static const lv_image_dsc_t {name} = {{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565,.w={sized.width},.h={sized.height},.stride={sized.width*2}}},.data_size={len(data)},.data={name}_data}};')
        descriptors.append(f'{{&photo_{n}_0,&photo_{n}_1}}')
    code.append('const lv_image_dsc_t *const passport_photos[6][2] = {'+','.join(descriptors)+'};')
    (DEST/'passport_photos.c').write_text('\n'.join(code)+'\n',encoding='utf-8')
    print('Photo examples: generated 6 scenes, normal/fullscreen RGB565 variants')

if __name__=='__main__':
    main()
