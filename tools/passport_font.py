#!/usr/bin/env python3
"""Generate/check the application's plain 4bpp LVGL fonts.

Generation needs Pillow 11.3.0 and fonttools 4.60.1; checking needs only Python.
Each glyph is byte-aligned, with continuous (not row-padded) high-first nibbles.
"""
from __future__ import annotations
import argparse
import ast
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/fonts"
SOURCE = ASSETS / "NotoSansSC-wght.ttf"
MANIFEST = ASSETS / "passport-fonts.json"
SIZES = (12, 16, 20)

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def codepoints():
    text = (ROOT / "main/passport_text.h").read_text(encoding="utf-8")
    strings = re.findall(r'^#define\s+\w+\s+("(?:[^"\\]|\\.)*")', text, re.M)
    return sorted(set(range(32, 127)) | {
        ord(c) for s in strings for c in ast.literal_eval(s) if ord(c) >= 32
    })

def generate_font(size, points):
    from PIL import Image, ImageDraw, ImageFont
    from fontTools.ttLib import TTFont
    source = TTFont(SOURCE)
    supported = source.getBestCmap()
    assert all(cp in supported for cp in points), "Source font lacks required glyphs"
    font = ImageFont.truetype(str(SOURCE), size)
    # The variable font's default axis is Thin (100). Use regular weight for
    # legible Chinese strokes on the small physical display.
    font.set_variation_by_axes([400])
    bitmap = bytearray()
    expected_pixels = []
    descriptors = ["    {0},"]
    minimum_y, maximum_y = 0, 0
    for cp in points:
        char = chr(cp)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        w, h = right - left, bottom - top
        image = Image.new("L", (max(w, 1), max(h, 1)))
        ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
        pixels = [int(v) >> 4 for v in image.getdata()] if w and h else []
        start = len(bitmap)
        packed = bytearray((pixels[i] << 4) | (pixels[i+1] if i+1 < len(pixels) else 0)
                           for i in range(0, len(pixels), 2))
        # Decode the stored format back and compare every pixel, including odd
        # widths and odd glyph pixel counts. No compressed-font decoder needed.
        decoded = [n for b in packed for n in (b >> 4, b & 15)][:len(pixels)]
        assert decoded == pixels
        bitmap.extend(packed)
        expected_pixels.append((start, pixels))
        advance = round(font.getlength(char) * 16)
        descriptors.append(f"    {{.bitmap_index={start}, .adv_w={advance}, .box_w={w}, .box_h={h}, .ofs_x={left}, .ofs_y={-bottom}}},")
        minimum_y, maximum_y = min(minimum_y, top), max(maximum_y, bottom)
    rows = [", ".join(f"0x{v:02x}" for v in bitmap[i:i+16]) for i in range(0, len(bitmap), 16)]
    offsets = ", ".join(str(cp-points[0]) for cp in points)
    bitmap_text = ",\n    ".join(rows)
    output = f'''/* Generated by tools/passport_font.py; Noto Sans SC, SIL OFL 1.1. */
#include "lvgl.h"
static const uint8_t glyph_bitmap[] = {{
    {bitmap_text}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(descriptors)}
}};
static const uint16_t unicode_list[] = {{{offsets}}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start={points[0]}, .range_length={points[-1]-points[0]+1}, .glyph_id_start=1,
      .unicode_list=unicode_list, .list_length={len(points)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps,
    .cmap_num=1, .bpp=4, .bitmap_format=0
}};
const lv_font_t passport_font_{size} = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height={maximum_y-minimum_y+2}, .base_line={maximum_y+1},
    .subpx=LV_FONT_SUBPX_NONE, .underline_position=-2, .underline_thickness=1,
    .dsc=&font_dsc
}};
'''
    # Keep generation paths/platforms out of the reproducible artifact.
    destination = ASSETS / f"passport_font_{size}.c"
    destination.write_text(output, encoding="utf-8", newline="\n")
    # Reparse the serialized C, then decode exactly the PLAIN format consumed
    # by LVGL. This checks the file that is compiled, not just a temporary pack.
    serialized = destination.read_text(encoding="utf-8")
    block = re.search(r'glyph_bitmap\[\] = \{(.*?)\};', serialized, re.S)[1]
    stored = bytes(int(v, 16) for v in re.findall(r'0x([0-9a-f]{2})', block))
    assert stored == bitmap
    for start, pixels in expected_pixels:
        decoded = [n for b in stored[start:start+(len(pixels)+1)//2]
                   for n in (b >> 4, b & 15)][:len(pixels)]
        assert decoded == pixels, "Serialized font bitmap mismatch"

def check():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    assert manifest["codepoints"] == codepoints(), "UI text changed: regenerate fonts"
    for name, sha in manifest["sha256"].items():
        assert digest(ROOT / name) == sha, f"Font artifact changed: {name}"
    for size in SIZES:
        text = (ASSETS / f"passport_font_{size}.c").read_text(encoding="utf-8")
        offsets = re.search(r'unicode_list\[\] = \{([^}]+)', text)[1]
        points = [int(v.strip())+32 for v in offsets.split(",")]
        assert points == codepoints() and 0x9f98 not in points
        assert len(re.findall(r'\.bitmap_index=', text)) == len(points)
    print(f"Font coverage: PASS ({len(codepoints())} glyphs at 12/16/20 px; U+9F98 absent)")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.generate:
        import PIL
        import fontTools
        assert PIL.__version__ == "11.3.0" and fontTools.__version__ == "4.60.1"
        points = codepoints()
        for size in SIZES:
            generate_font(size, points)
        inventory = "#pragma once\n#include <stdint.h>\nstatic const uint32_t passport_codepoints[] = {" + ",".join(map(str, points)) + "};\n"
        (ROOT / "main/passport_font_inventory.h").write_text(inventory, encoding="utf-8", newline="\n")
        files = [SOURCE, *(ASSETS / f"passport_font_{size}.c" for size in SIZES), ROOT / "main/passport_font_inventory.h", Path(__file__)]
        manifest = {"generator": "Pillow 11.3.0 / fonttools 4.60.1; weight 400; plain 4bpp",
                    "codepoints": points, "sha256": {p.relative_to(ROOT).as_posix(): digest(p) for p in files}}
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    check()

if __name__ == "__main__":
    main()
